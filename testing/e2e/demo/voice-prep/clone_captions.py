"""Caption cues for the cloned clips, and a fresh ../narration-<demo>.mjs.

  python -I clone_captions.py WORK      (any Python 3; reads WORK\\final_words.json from verify_clones.py)
Caption text is the script line ('caption' if given, else 'say'), split into short phrases exactly as
captions.py does, each timed to the first word's start in the clip.
"""
import difflib
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
work = Path(sys.argv[1])
DEMO = os.environ.get("DEMO", "app1")
SPEC = json.loads((HERE / f"{DEMO}-lines.json").read_text(encoding="utf-8"))
spec = [line for scene in SPEC["scenes"] for line in scene["lines"]]
words = json.loads((work / "final_words.json").read_text(encoding="utf-8"))
SCENES = [(scene["scene"], [line[0] for line in scene["lines"]]) for scene in SPEC["scenes"]]

# ---- phrase splitting: same rules as captions.py ----
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())
MAX = 64


def split_long(p):
    ws = p.split()
    if len(p) <= MAX + 12:
        return [p]
    joins = [k for k, w in enumerate(ws) if w.lower() in ("and", "without", "so", "which", "but", "on", "to") and 2 < k < len(ws) - 2]
    k = min(joins, key=lambda k: abs(k - len(ws) / 2)) if joins else len(ws) // 2
    return split_long(" ".join(ws[:k])) + split_long(" ".join(ws[k:]))


def pack(parts):
    out, cur = [], ""
    for p in parts:
        if cur and len(cur) + 1 + len(p) > MAX:
            out.append(cur)
            cur = p
        else:
            cur = f"{cur} {p}".strip()
    return out + [cur] if cur else out


def phrases(text):
    out, cur = [], ""
    for s in re.split(r"(?<=[.?])\s+", text):
        if len(f"{cur} {s}".strip()) <= MAX:
            cur = f"{cur} {s}".strip()
            continue
        if cur:
            out.append(cur)
            cur = ""
        if len(s) <= MAX:
            cur = s
            continue
        clauses = [q for c in re.split(r"(?<=[,:])\s+", s) for q in split_long(c)]
        packed = pack(clauses)
        out += packed[:-1]
        cur = packed[-1]
    return out + [cur] if cur else out


# ---- timing: each phrase starts at its first word's time in the clip ----
cues = {}
for id_, say, caption in spec:
    text = caption or say
    asr = words[id_]
    a = [norm(w[2]) for w in asr]
    c = [norm(w) for w in say.split()]  # match on what was SAID (numbers in words), then map phrases by word count
    sm = difflib.SequenceMatcher(a=c, b=a, autojunk=False)
    m = {blk.a + k: blk.b + k for blk in sm.get_matching_blocks() for k in range(blk.size)}

    def t_of(ci):
        if ci in m:
            return asr[m[ci]][0]
        lo = max([k for k in m if k < ci], default=None)
        hi = min([k for k in m if k > ci], default=None)
        tl = asr[m[lo]][1] if lo is not None else 0.0
        th = asr[m[hi]][0] if hi is not None else asr[-1][1]
        nl = lo if lo is not None else -1
        nh = hi if hi is not None else len(c)
        return tl + (th - tl) * (ci - nl) / max(1, nh - nl)

    # a caption phrase's first word -> the index of the same word in `say` (digits in captions differ)
    # Matched on the phrase's first two words in order, after the previous phrase's start: a single word
    # ("in", "the", "and") also occurs earlier in the line.
    say_words = [norm(w) for w in say.split()]
    out, idx = [], 0
    for k, p in enumerate(phrases(text)):
        head = [norm(w) for w in p.split()[:2]]
        if k:
            hits = [j for j in range(idx + 1, len(say_words))
                    if say_words[j:j + len(head)] == head]
            assert hits, f"{id_}: can't place caption phrase '{p}' in the spoken line"
            idx = hits[0]
        out.append([0.0 if k == 0 else round(max(0, t_of(idx) - 0.1), 2), p])
    cues[id_] = out
    print(f"{id_} " + " | ".join(f"{t:.1f} {p}" for t, p in out))

# ---- narration file ----
text_of = {i: (cap or say) for i, say, cap in spec}
js = ["// The demo video's script: one entry per voice clip, demo/voice/<demo>/<id>.wav. Generated by",
      "// voice-prep/clone_captions.py from the lines file: edit that, not this. Each entry is [id, caption text, cues],",
      "// where cues are [seconds into the clip, caption text], timed from the clip's word timestamps.",
      "export const scenes = ["]
for name, ids in SCENES:
    js.append(f'  {{ scene: "{name}", lines: [')
    for i in ids:
        js.append(f"    [{json.dumps(i)}, {json.dumps(text_of[i], ensure_ascii=False)},")
        js.append(f"      {json.dumps(cues[i], ensure_ascii=False)}],")
    js.append("  ] },")
js += ["];",
       "export const allLines = scenes.flatMap((s) => s.lines.map(([id, text, cues]) => ({ id, text, cues, scene: s.scene })));",
       ""]
(HERE.parent / f"narration-{DEMO}.mjs").write_text("\n".join(js), encoding="utf-8", newline="\n")
print(f"wrote narration-{DEMO}.mjs")
